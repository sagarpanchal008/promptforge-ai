"""
==============================================================================
FILE: agents/reviewer_agent.py
PURPOSE:
    Agent 5: Quality Reviewer.
    Inspects the optimized prompt generated by Agent 4.
    Conducts comparative critique against initial weaknesses.
    Decides via LangGraph conditional edges whether to APPROVE or request
    a REVISION cycle (cyclic multi-agent workflow).
==============================================================================
"""

from typing import Dict
from agents.state import PromptAgentState


def review_optimized_prompt(state: PromptAgentState) -> Dict:
    """
    Agent 5 Node: Evaluates optimized prompt quality and makes routing decision.
    """
    optimized = state.get("optimized_prompt", "")
    iteration = state.get("iteration_count", 0) + 1
    max_iter = state.get("max_iterations", 2)
    weaknesses = state.get("detected_weaknesses", [])

    word_count = len(optimized.split())
    critique_points = []

    # Quality Gate 1: Word Count & Depth
    if word_count < 30:
        critique_points.append("Optimized prompt remains too concise; needs deeper structural elaboration.")

    # Quality Gate 2: Persona Check
    if not any(k in optimized.lower() for k in ["act as", "you are", "role", "expert"]):
        critique_points.append("Prompt lacks explicit persona anchor.")

    # Quality Gate 3: Structural Formatting
    if not any(k in optimized for k in ["1.", "2.", "-", "*", "##", "Section"]):
        critique_points.append("Prompt lacks hierarchical formatting (numbered lists or markdown headers).")

    # Routing Decision
    if critique_points and iteration < max_iter:
        status = "NEEDS_REVISION"
        critique = " | ".join(critique_points)
    else:
        status = "APPROVED"
        critique = "All structural quality rubrics satisfied. The prompt is production-ready."

    return {
        "review_status": status,
        "review_critique": critique,
        "iteration_count": iteration,
    }


def should_continue_review(state: PromptAgentState) -> str:
    """
    Conditional Edge Function for LangGraph:
    Routes to 'prompt_optimizer' if review_status == 'NEEDS_REVISION'.
    Routes to 'final_agent' if review_status == 'APPROVED'.
    """
    status = state.get("review_status", "APPROVED")
    if status == "NEEDS_REVISION":
        return "needs_revision"
    return "approved"


if __name__ == "__main__":
    test_state = {
        "optimized_prompt": "Act as an expert. 1. Do this. 2. Do that. Output format: Markdown.",
        "iteration_count": 0,
        "max_iterations": 2,
    }
    res = review_optimized_prompt(test_state)
    print("Agent 5 Review:", res)
    print("Conditional Route:", should_continue_review(res))
